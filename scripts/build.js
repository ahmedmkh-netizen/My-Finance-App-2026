// Pre-compiles the JSX in index.src.html so the phone does not compile 18,000 lines on every open.
// Usage:  npm i --no-save @babel/core @babel/preset-react   then   node scripts/build.js
// index.src.html = the file you edit. index.html = generated, never edit by hand.
const fs = require("fs");
const babel = require("@babel/core");
const src = fs.readFileSync("index.src.html", "utf8");
const crlf = src.includes("\r\n");
const text = src.replace(/\r\n/g, "\n");
const re = /<script type="text\/babel" data-type="module">\n([\s\S]*?)\n\s*<\/script>/;
const m = text.match(re);
if (!m) throw new Error("babel script block not found");
const out = babel.transformSync(m[1], { presets: [["@babel/preset-react", { runtime: "classic" }]], compact: false, comments: false, sourceType: "module", filename: "app.jsx" }).code;
let html = text.replace(re, () => '<script type="module">\n' + out.replace(/<\/script>/g, "<\\/script>") + "\n    </script>");
html = html.replace(/\s*<script src="https:\/\/unpkg\.com\/@babel\/standalone\/babel\.min\.js"><\/script>\n/, "\n");
html = html.replace("<head>", "<head>\n    <!-- GENERATED from index.src.html by scripts/build.js. Do not edit this file directly. -->");
fs.writeFileSync("index.html", crlf ? html.replace(/\n/g, "\r\n") : html);
console.log("built index.html", html.length, "bytes from", text.length);
